"""
nightmare_activation.py — One-time online licence activation, Suite side
=========================================================================
Admin copy only for now. Do NOT seal/deploy until Caleb approves.

This module does NOT invent a new key format. It reuses the Suite's own
validators, so a key generated by the Cloudflare Worker validates here,
and a key generated by the Suite validates there:

  - shield keys: core_mind.ghostrider_shield.validate_key_format,
    seal_license_key, verify_license_key
  - ND- keys: core_mind.license_crypto.validate_license (Ed25519, HWID, expiry)

Flow:
  1. Customer enters a key in Help -> Enter License Key.
  2. Suite POSTs {key, hwid} once to https://ntmre.com/activate
     (Cloudflare Worker, see suite/cloudflare-worker/worker.js).
  3. Worker verifies the key against Suite formats + its internal KV list,
     marks it used, binds it to that HWID, and returns an activation token.
  4. Suite stores the token in nightmare_suite/.activation (JSON, local only).
  5. On later startups, Suite checks offline: token.hwid == local HWID,
     token.key_hash == seal_license_key(key), token.tier == format tier.
     No internet needed to run after activation.
  6. If the same key is entered on another machine, that machine's one-time
     online check fails (already used on another HWID), so pass-around is
     blocked at activation, not at runtime.

No key, token, or HWID is ever printed by this module. Callers must not
log the key or the activation token.
"""

import hashlib
import hmac
import json
import os
import sys
import urllib.request
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(APP_DIR))

ACTIVATE_URL = os.environ.get("NIGHTMARE_ACTIVATE_URL", "https://ntmre.com/activate")
ACTIVATION_FILE = APP_DIR / "nightmare_suite" / ".activation"


def get_hwid_hex():
    """Local machine HWID, same source as license_crypto.get_hwid_hex."""
    try:
        from core_mind.license_crypto import get_hwid_hex as _gh
        return _gh()
    except Exception:
        # Fallback: stable hash of machine identifiers, for activation only.
        # This is NOT the ND- HWID; ND- HWID binding is checked by
        # license_crypto itself, not by this fallback.
        import platform
        raw = f"{platform.node()}|{platform.machine()}|{platform.system()}".encode()
        return hashlib.sha256(raw).hexdigest()[:24]


def _format_tier(key):
    try:
        from core_mind.ghostrider_shield import validate_key_format
        tier = validate_key_format(key)
        if tier is not None:
            return tier
    except Exception:
        pass
    try:
        from core_mind.license_crypto import validate_license
        return validate_license(key)
    except Exception:
        return None


def _sealed_hash(key):
    try:
        from core_mind.ghostrider_shield import seal_license_key
        return seal_license_key(key)
    except Exception:
        return hashlib.sha256(key.encode()).hexdigest()


def activate_once(key, url=ACTIVATE_URL):
    """One-time online activation. Returns (tier, activation_dict) or raises."""
    hwid = get_hwid_hex()
    payload = json.dumps({"key": key, "hwid": hwid}).encode()
    req = urllib.request.Request(url, data=payload, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        data = json.loads(resp.read().decode())
    if not data.get("ok"):
        raise ValueError(data.get("error", "activation_failed"))
    activation = data["activation"]
    # Verify, offline, against the Suite's own validators before storing.
    if activation.get("tier") != _format_tier(key):
        raise ValueError("tier_mismatch")
    if activation.get("hwid", "").lower() != hwid.lower():
        raise ValueError("hwid_mismatch")
    if activation.get("key_hash") != _sealed_hash(key):
        raise ValueError("key_hash_mismatch")
    ACTIVATION_FILE.parent.mkdir(parents=True, exist_ok=True)
    ACTIVATION_FILE.write_text(json.dumps(activation))
    return activation["tier"], activation


def verify_offline_activation(key):
    """Offline check on startup. Returns tier or None. No network."""
    if not ACTIVATION_FILE.exists():
        return None
    try:
        activation = json.loads(ACTIVATION_FILE.read_text())
    except Exception:
        return None
    if activation.get("hwid", "").lower() != get_hwid_hex().lower():
        return None
    if activation.get("key_hash") != _sealed_hash(key):
        return None
    tier = activation.get("tier")
    if tier != _format_tier(key):
        return None
    return tier
